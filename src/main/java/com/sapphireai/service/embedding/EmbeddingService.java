package com.sapphireai.service.embedding;

import com.sapphireai.model.entity.DocumentChunk;
import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.cache.annotation.Cacheable;
import org.springframework.stereotype.Service;

import java.util.List;

/**
 * Embedding service with dual-embedder strategy.
 *
 * STRATEGY:
 * - Auto: Try HuggingFace (fast), fall back to Ollama (reliable)
 * - HuggingFace: Force HuggingFace only
 * - Ollama: Force Ollama only
 *
 * OBSERVABILITY:
 * - Metrics: embedding_time, embedding_fallback_count
 * - Logs: Which embedder used, why fallback triggered
 */
@Service
@Slf4j
public class EmbeddingService {

    private final Embedder primaryEmbedder;
    private final Embedder fallbackEmbedder;
    private final String strategy;

    private final Timer embeddingTimer;
    private final Counter fallbackCounter;

    public EmbeddingService(
            @Autowired(required = false) HuggingFaceEmbedder huggingFaceEmbedder,
            OllamaEmbedder ollamaEmbedder,
            @Value("${sapphire.embedding.provider:auto}") String strategy,
            MeterRegistry meterRegistry
    ) {
        this.strategy = strategy;

        // Select embedders based on strategy
        if ("huggingface".equalsIgnoreCase(strategy)) {
            if (huggingFaceEmbedder == null || !huggingFaceEmbedder.isAvailable()) {
                throw new IllegalStateException("HuggingFace embedder requested but not available");
            }
            this.primaryEmbedder = huggingFaceEmbedder;
            this.fallbackEmbedder = ollamaEmbedder;
            log.info("Embedding strategy: HuggingFace primary, Ollama fallback");

        } else if ("ollama".equalsIgnoreCase(strategy)) {
            this.primaryEmbedder = ollamaEmbedder;
            this.fallbackEmbedder = huggingFaceEmbedder;
            log.info("Embedding strategy: Ollama primary, HuggingFace fallback");

        } else { // auto
            // Auto-select based on availability
            if (huggingFaceEmbedder != null && huggingFaceEmbedder.isAvailable()) {
                this.primaryEmbedder = huggingFaceEmbedder;
                this.fallbackEmbedder = ollamaEmbedder;
                log.info("Embedding strategy: AUTO selected HuggingFace (available)");
            } else {
                this.primaryEmbedder = ollamaEmbedder;
                this.fallbackEmbedder = huggingFaceEmbedder;
                log.info("Embedding strategy: AUTO selected Ollama (HuggingFace unavailable)");
            }
        }

        // Metrics
        this.embeddingTimer = Timer.builder("embedding.generation.time")
                .description("Time to generate embeddings")
                .tag("provider", primaryEmbedder.getModelName())
                .register(meterRegistry);

        this.fallbackCounter = Counter.builder("embedding.fallback.count")
                .description("Number of fallback embeddings")
                .register(meterRegistry);
    }

    /**
     * Generate embedding with automatic fallback.
     * Cached to avoid redundant computation.
     */
    @Cacheable(value = "embeddings", key = "#text", unless = "#result == null")
    public float[] generateEmbedding(String text) {
        return embeddingTimer.record(() -> {
            try {
                float[] result = primaryEmbedder.embed(text);
                log.debug("Embedding generated by: {}", primaryEmbedder.getModelName());
                return result;

            } catch (Exception primaryError) {
                log.warn("Primary embedder failed: {}. Trying fallback...", primaryError.getMessage());
                fallbackCounter.increment();

                if (fallbackEmbedder == null) {
                    log.error("No fallback embedder available");
                    throw new RuntimeException("Embedding generation failed and no fallback available", primaryError);
                }

                try {
                    float[] result = fallbackEmbedder.embed(text);
                    log.info("Embedding generated by fallback: {}", fallbackEmbedder.getModelName());
                    return result;

                } catch (Exception fallbackError) {
                    log.error("Both embedders failed", fallbackError);
                    throw new RuntimeException("Embedding generation failed completely", fallbackError);
                }
            }
        });
    }

    /**
     * Get active embedder dimension.
     * CRITICAL: Must match Qdrant collection vector size.
     */
    public int getEmbeddingDimension() {
        return primaryEmbedder.getDimension();
    }

    /**
     * Get active embedder model name.
     */
    public String getActiveModel() {
        return primaryEmbedder.getModelName();
    }

    /**
     * Batch embed chunks (optimized).
     */
    public void embedChunks(List<DocumentChunk> chunks) {
        log.info("Embedding {} chunks using {}", chunks.size(), primaryEmbedder.getModelName());

        for (DocumentChunk chunk : chunks) {
            float[] embedding = generateEmbedding(chunk.getContent());
            // Store embedding in chunk for indexing
            chunk.setEmbedding(embedding);
            // Store embedding dimension for validation
            chunk.setTokenCount(embedding.length);
        }

        log.info("Completed embedding {} chunks", chunks.size());
    }
}